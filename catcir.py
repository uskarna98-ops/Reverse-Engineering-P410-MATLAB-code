def split_segments(log, gap_factor=3.0):
    """Split at large jumps in the radio timestamp (radio stopped/restarted).
    Returns list of (start, stop) index pairs."""
    d = np.diff(log.dev_ts)
    thr = np.median(d) * gap_factor
    cuts = np.where(d > thr)[0] + 1
    edges = [0, *cuts.tolist(), len(log.dev_ts)]
    return list(zip(edges[:-1], edges[1:]))


def time_axis_ns(n_samples, step_bins=None):
    step_bins = step_bins or STEP_BINS
    return np.arange(n_samples) * step_bins * BIN_PS / 1000.0


def path_axis_m(n_samples, step_bins=None):
    """Bistatic path-length (tx->target->rx) relative to bin 0, meters."""
    return time_axis_ns(n_samples, step_bins) * 1e-9 * C


# ----------------------------------------------------------------- filtering
def remove_dc(x):
    return x - x.mean(axis=1, keepdims=True)


def background_mean(x):
    """Subtract the long-term mean scan (static clutter)."""
    return x - x.mean(axis=0, keepdims=True)


def background_ema(x, alpha=0.02):
    """Adaptive (exponential) background subtraction; tracks slow drift."""
    out = np.empty_like(x)
    bg = x[0].copy()
    for i, s in enumerate(x):
        out[i] = s - bg
        bg = (1 - alpha) * bg + alpha * s
    return out


def background_loopback(x, k=1):
    """k-th scan difference (a simple MTI canceller)."""
    out = np.zeros_like(x)
    out[k:] = x[k:] - x[:-k]
    return out


def svd_clutter_removal(x, n_remove=1):
    """Remove the strongest n_remove singular components (static clutter and
    slow common drift). Operates on a (scans x samples) matrix."""
    xm = x - x.mean(axis=0, keepdims=True)
    u, s, vt = np.linalg.svd(xm, full_matrices=False)
    s2 = s.copy()
    s2[:n_remove] = 0
    return (u * s2) @ vt


def slow_time_highpass(x, fs, fc=0.2, order=3):
    """High-pass each range bin along slow time (removes stationary returns)."""
    from scipy.signal import butter, sosfiltfilt
    sos = butter(order, fc, btype="highpass", fs=fs, output="sos")
    return sosfiltfilt(sos, x, axis=0)


def fast_time_smooth(x, width=5):
    """Matched-filter-like smoothing along range (fast time). Replace the
    kernel with the transmit template for a true matched filter."""
    from scipy.signal import savgol_filter
    return savgol_filter(x, window_length=width | 1, polyorder=2, axis=1)


def coherent_average(x, n):
    """Average n consecutive scans -> sqrt(n) noise reduction (3 dB per doubling)
    for stationary targets. Returns (n_scans//n, n_samples)."""
    m = (len(x) // n) * n
    return x[:m].reshape(-1, n, x.shape[1]).mean(axis=1)


def envelope(x):
    from scipy.signal import hilbert
    return np.abs(hilbert(x, axis=1))


# ----------------------------------------------------------------- detection
def ca_cfar(env, guard=4, train=16, pfa_scale=3.0):
    """Cell-averaging CFAR along range for each scan. Returns boolean mask."""
    n = env.shape[1]
    kernel = np.zeros(2 * (guard + train) + 1)
    kernel[:train] = 1
    kernel[-train:] = 1
    kernel /= kernel.sum()
    noise = np.apply_along_axis(lambda r: np.convolve(r, kernel, mode="same"), 1, env)
    return env > pfa_scale * noise


PIPELINES = {
    "mean":  lambda x, fs, a: background_mean(remove_dc(x)),
    "ema":   lambda x, fs, a: background_ema(remove_dc(x), alpha=a.alpha),
    "diff":  lambda x, fs, a: background_loopback(remove_dc(x)),
    "svd":   lambda x, fs, a: svd_clutter_removal(remove_dc(x), a.n_remove),
    "hp":    lambda x, fs, a: slow_time_highpass(remove_dc(x), fs, a.fc),
}


def process(log, method="svd", average=1, smooth=0, args=None):
    """Return list of dicts, one per continuous segment."""
    args = args or argparse.Namespace(alpha=0.02, n_remove=1, fc=0.2)
    out = []
    for a, b in split_segments(log):
        x = log.scans[a:b]
        t = (log.dev_ts[a:b] - log.dev_ts[a]) / 1000.0     # seconds (assumes ms)
        fs = 1.0 / np.median(np.diff(t)) if len(t) > 1 else 1.0
        if average > 1:
            x = coherent_average(x, average)
            t = t[: len(x) * average].reshape(-1, average).mean(axis=1)
            fs /= average
        y = PIPELINES[method](x, fs, args)
        if smooth:
            y = fast_time_smooth(y, smooth)
        env = envelope(y)
        out.append(dict(segment=(a, b), t=t, fs=fs, raw=x, filtered=y,
                        envelope=env, detections=ca_cfar(env)))
    return out


def plot(results, log, path, show=False):
    import matplotlib
    if not show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    n = len(results)
    fig, ax = plt.subplots(2, n, figsize=(7 * n, 8), squeeze=False)
    rng = path_axis_m(log.scans.shape[1], log.meta.get("step_bins") or None)
    for i, r in enumerate(results):
        ext = [rng[0], rng[-1], r["t"][-1], r["t"][0]]
        ax[0, i].imshow(r["raw"], aspect="auto", extent=ext, cmap="seismic")
        ax[0, i].set_title(f"raw, segment {r['segment']}")
        ax[1, i].imshow(r["envelope"], aspect="auto", extent=ext, cmap="viridis")
        ax[1, i].set_title("filtered envelope")
        for a_ in ax[:, i]:
            a_.set_xlabel("sample index x spacing -> path (m)  [assumed]")
            a_.set_ylabel("slow time (s)")
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    if show:
        plt.show()


def run(path=None, method=METHOD, average=AVERAGE, smooth=SMOOTH,
        alpha=0.02, n_remove=1, fc=0.2, plot_path="radar_plot.png", show=True):
    """Call this from a notebook cell: run()  or  run('/content/drive/.../x.csv')"""
    path = path or FILE_PATH or find_logfile()
    print("Loading:", path)
    log = load_cat_log(path)
    print("scans:", log.scans.shape, "meta:", log.meta)
    print("segments:", split_segments(log))
    args = argparse.Namespace(alpha=alpha, n_remove=n_remove, fc=fc)
    res = process(log, method, average, smooth, args)
    for r in res:
        print(f"segment {r['segment']}: {len(r['t'])} scans, fs={r['fs']:.2f} Hz, "
              f"CFAR hits={int(r['detections'].sum())}")
    plot(res, log, plot_path, show=show)
    return log, res


