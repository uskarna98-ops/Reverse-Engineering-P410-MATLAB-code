def iir_tapped(x, b, a, matlab_start=False):
    """Explicit delay-tap loop: y[n] = sum b[k]x[n-k] - sum a[m]y[n-m], filtering along axis 0."""
    x = np.asarray(x, dtype=float)
    x2 = x.reshape(len(x), -1)
    y = np.zeros_like(x2)
    order = max(len(b), len(a)) - 1
    for n in range(order if matlab_start else 0, len(x2)):
        acc = np.zeros(x2.shape[1])
        for k in range(len(b)):
            if n - k >= 0:
                acc += b[k] * x2[n - k]
        for m in range(1, len(a)):
            if n - m >= 0:
                acc -= a[m] * y[n - m]
        y[n] = acc
    return y.reshape(x.shape)

# ============ Part A: delay taps from the frequency response ============
required = dict(FREQ_COL=FREQ_COL, FREQ_UNIT=FREQ_UNIT, MAG_COL=MAG_COL,
                PHASE_COL=PHASE_COL, PHASE_UNIT=PHASE_UNIT)
missing = [k for k, v in required.items() if v is None]
if missing:
    raise ValueError(f"Set these in SETTINGS before running Part A: {missing}")

unit_scale = {"Hz": 1.0, "kHz": 1e3, "MHz": 1e6, "GHz": 1e9}
if FREQ_UNIT not in unit_scale or PHASE_UNIT not in ("rad", "deg"):
    raise ValueError("FREQ_UNIT must be Hz/kHz/MHz/GHz and PHASE_UNIT must be rad/deg")

d = df[[FREQ_COL, MAG_COL, PHASE_COL]].apply(pd.to_numeric, errors="coerce").dropna()
d = d.sort_values(FREQ_COL)
f   = d[FREQ_COL].to_numpy(float) * unit_scale[FREQ_UNIT]
mag = d[MAG_COL].to_numpy(float)
ph  = d[PHASE_COL].to_numpy(float)
if PHASE_UNIT == "deg":
    ph = np.deg2rad(ph)

H = mag * np.exp(1j * ph)

df_hz = np.median(np.diff(f))
spacing_err = np.max(np.abs(np.diff(f) - df_hz)) / df_hz
print(f"{len(f)} frequency points, step = {df_hz:.6g} Hz, "
      f"range {f[0]:.6g} to {f[-1]:.6g} Hz, max step deviation = {spacing_err:.2%}")
if spacing_err > 1e-3:
    print("WARNING: frequency grid is not uniform; IFFT delays will be inaccurate. Resample first.")

n_missing = int(round(f[0] / df_hz))                    # zero-fill bins below the first frequency
H_full = np.concatenate([np.zeros(n_missing, dtype=complex), H])

h_time = np.fft.irfft(H_full)
N = len(h_time)
dt = 1.0 / (N * df_hz)
t = np.arange(N) * dt

env = np.abs(signal.hilbert(h_time))
peaks, _ = signal.find_peaks(env, height=TAP_THRESHOLD_FRAC * env.max(),
                             distance=MIN_TAP_SPACING)
tap_delays = t[peaks]
tap_amps = h_time[peaks]

fig, ax = plt.subplots(2, 1, figsize=(10, 7), sharex=True)
ax[0].plot(t * 1e9, h_time, lw=0.8, label="Channel impulse response")
ax[0].plot(t * 1e9, env, "--", lw=0.8, label="Envelope")
ax[0].legend(); ax[0].grid(True); ax[0].set_title("Wideband channel impulse response")
ax[1].stem(tap_delays * 1e9, tap_amps)
ax[1].set_title(f"Extracted delay taps ({len(peaks)})")
ax[1].set_xlabel("Delay (ns)"); ax[1].set_ylabel("Tap amplitude"); ax[1].grid(True)
plt.tight_layout(); plt.show()

print("Tap #   delay (ns)   amplitude")
for k, (dly, amp) in enumerate(zip(tap_delays, tap_amps)):
    print(f"{k:4d}   {dly*1e9:10.3f}   {amp: .4e}")