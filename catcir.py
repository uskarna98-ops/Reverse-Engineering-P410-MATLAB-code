def load_cat_log(path):
    """Read a CAT .csv logfile. Header lines are repeated before the first
    instance of each message type, and rows are padded with empty commas.
    Rows are classified by their second field; anything that does not parse
    (header lines, truncated last line, Excel-resaved oddities) is skipped
    and counted so problems are visible."""
    scans, host_ts, dev_ts = [], [], []
    meta, config, events = {}, {}, []
    counts, skipped = {}, 0
    # utf-8-sig strips the BOM that Excel adds, which otherwise breaks the
    # "Timestamp" header check on the first line.
    with open(path, newline="", encoding="utf-8-sig", errors="replace") as f:
        for row in csv.reader(f):
            if len(row) < 2:
                continue
            name = row[1].strip()
            counts[name] = counts.get(name, 0) + 1
            try:
                if name == "CatFullScanInfo":
                    n = int(row[16])                       # header row raises here
                    data = row[SCAN_DATA_COL:SCAN_DATA_COL + n]
                    if len(data) < n:                      # truncated line
                        skipped += 1
                        continue
                    scans.append(np.asarray(data, dtype=np.float32))
                    host_ts.append(float(row[0]))
                    dev_ts.append(float(row[4]))
                    if not meta:
                        meta = dict(scan_start=int(row[10]), scan_stop=int(row[11]),
                                    step_bins=int(row[12]), filtering=int(row[13]),
                                    antenna=int(row[14]), op_mode=int(row[15]),
                                    n_samples=n)
                elif name == "CatConfig" and row[0].strip() != "Timestamp":
                    vals = [c.strip() for c in row if c.strip() != ""]
                    config = dict(zip(CONFIG_FIELDS, vals[1:]))
                    config["host_ts"] = row[0]
                elif name == "CatMsg_ControlRequest" and row[0].strip() != "Timestamp":
                    events.append((float(row[0]),
                                   "start" if row[3].strip() == "1" else "stop"))
            except (ValueError, IndexError):
                skipped += 1                               # header or damaged row

    if not scans:
        raise ValueError(
            f"No scan rows parsed from '{path}'. Message types seen: {counts}. "
            "If 'CatFullScanInfo' is missing, this is not a CAT log with scans "
            "(scans are only logged after Show Plot + Start Scanning).")
    # keep only scans with the dominant length (guards against mixed lengths)
    lens = np.array([len(s) for s in scans])
    keep = lens == np.bincount(lens).argmax()
    scans = [s for s, k in zip(scans, keep) if k]
    host_ts = np.array(host_ts)[keep]
    dev_ts = np.array(dev_ts)[keep]
    print(f"parsed {len(scans)} scans; skipped {skipped} header/bad rows")
    return CatLog(np.vstack(scans), host_ts, dev_ts, meta, config, events)


